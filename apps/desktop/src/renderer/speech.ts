// 朗读前的 markdown 轻剥（§2.2 消息操作条 read aloud 的文本面，纯函数判卷）。
// 口径：宁少剥不误吞——只去最外层的常见标记（围栏/行内码/链接/标题/强调/引用/列表符），
// 剥完压掉连续空白。念的是内容不是记号：不该让人听到「井号」「星号星号」。

export function stripMarkdownForSpeech(md: string): string {
  let t = md;
  // 围栏代码：留下代码正文（念代码本身比念围栏标记有价值）；语言标签行去掉。
  t = t.replace(/```[^\n]*\n([\s\S]*?)```/g, "$1");
  t = t.replace(/```/g, "");
  // 行内码：去反引号留内容。
  t = t.replace(/`([^`\n]+)`/g, "$1");
  // 图片 → 替代文本；链接 → 锚文本（URL 不念）。
  t = t.replace(/!\[([^\]]*)\]\([^)]*\)/g, "$1");
  t = t.replace(/\[([^\]]+)\]\([^)]*\)/g, "$1");
  // 标题井号（行首）。
  t = t.replace(/^\s{0,3}#{1,6}\s+/gm, "");
  // 粗体 / 斜体（保内容去星号）。
  t = t.replace(/\*\*([^*\n]+)\*\*/g, "$1");
  t = t.replace(/(^|[^*])\*([^*\n]+)\*/g, "$1$2");
  t = t.replace(/__([^_\n]+)__/g, "$1");
  // 行首引用与列表符。
  t = t.replace(/^\s{0,3}>\s?/gm, "");
  t = t.replace(/^\s{0,3}[-*+]\s+/gm, "");
  t = t.replace(/^\s{0,3}\d+\.\s+/gm, "");
  // 水平线整行。
  t = t.replace(/^\s{0,3}(-{3,}|\*{3,})\s*$/gm, "");
  return t.replace(/\s+/g, " ").trim();
}
