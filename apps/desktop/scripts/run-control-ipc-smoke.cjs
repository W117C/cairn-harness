// 真实 Electron preload/IPC + 真实 host/脚本模型；审批保持未决，用来观察工作区控制归属。
// 不加载整应用，不代表应用启动通过。profile/workspaces 均隔离；不拨真实 Provider。
const { app, BrowserWindow, ipcMain } = require("electron");
const { mkdtempSync, mkdirSync, writeFileSync, rmSync } = require("node:fs");
const { tmpdir } = require("node:os");
const { join, resolve } = require("node:path");
const repo = resolve(__dirname, "../../..");
const profile = mkdtempSync(join(tmpdir(), "cairn-control-ipc-"));
const out = resolve(process.argv[2]); mkdirSync(out, { recursive: true });
app.setPath("userData", join(profile, "profile"));
app.on("quit", () => rmSync(profile, { recursive: true, force: true }));
for (const key of ["M3A_AGENTS_DEMO", "M1B_GATE_FLOW", "M1C_AUTONOMY_SCRIPT", "M0A_PROVIDER", "CAIRN_MODEL", "M0B_WORKSPACE"]) delete process.env[key];
process.env.M3A_MAIN_SCRIPT = join(repo, "fixtures/agents/main-approval-demo.jsonl");
require(require.resolve("tsx/cjs", { paths: [repo] }));
const { createKernelHost } = require("../src/main/kernel-host.ts");
const { createSession } = require(join(repo, "src/main/sessions.ts"));
const { INVOKE_CHANNELS } = require("../src/main/channels.ts");
const { IPC_PROTOCOL_VERSION } = require(join(repo, "src/main/ipc-protocol.ts"));
const checks = [];
const check = (name, ok) => { checks.push({ name, ok }); console.log(`${ok ? "PASS" : "FAIL"} ${name}`); };
let host;
async function main() {
  await app.whenReady();
  const a = join(profile, "a"), b = join(profile, "b"), userData = join(profile, "data");
  for (const dir of [a, b, userData]) mkdirSync(dir, { recursive: true });
  writeFileSync(join(userData, "settings.json"), JSON.stringify({ provider: "demo", model: "" }));
  for (const ws of [a, b]) await createSession(join(ws, ".agent", "sessions"), "same");
  let asked = false;
  host = createKernelHost({ workspaces: [a, b], activeWorkspace: a, userDataDir: userData, outbox: (channel) => { if (channel === "onAsk") asked = true; } });
  ipcMain.handle(INVOKE_CHANNELS.run, (_event, request) => host.run(request));
  ipcMain.handle(INVOKE_CHANNELS.runCancel, (_event, sid, workspace) => host.cancel(sid, workspace));
  ipcMain.handle(INVOKE_CHANNELS.runSteer, (_event, sid, text, workspace) => host.steer(sid, text, workspace));
  ipcMain.handle(INVOKE_CHANNELS.protocolVersion, () => IPC_PROTOCOL_VERSION);
  const win = new BrowserWindow({ show: false, webPreferences: { preload: process.env.CAIRN_CONTROL_PRELOAD || join(__dirname, "../dist-electron/preload.cjs") } });
  const errors = [];
  win.webContents.on("preload-error", (_event, _path, error) => errors.push(error.message));
  const js = (source) => win.webContents.executeJavaScript(source);
  await win.loadURL("data:text/html,<meta http-equiv='Content-Security-Policy' content=\"default-src 'none'\"><title>Run control IPC</title>");
  check("真实 preload 回读当前协议版本", await js("window.agent.protocolVersion()") === IPC_PROTOCOL_VERSION);
  await js(`window.activeRun = window.agent.run(${JSON.stringify({ sessionId: "same", workspace: a, message: "hold at approval", mode: "default" })}); true;`);
  for (let attempt = 0; !asked && attempt < 150; attempt++) await new Promise((r) => setTimeout(r, 50));
  if (!asked) throw new Error("脚本运行未进入真实审批门");
  check("真实运行停在审批门等待，只有一场执行", host.runningCount() === 1);
  const wrongSteer = await js(`window.agent.runSteer('same', 'B must not reach A', ${JSON.stringify(b)})`);
  const wrongCancel = await js(`window.agent.runCancel('same', ${JSON.stringify(b)})`);
  check("错误工作区插话与停止均被真实 host 拒绝", !wrongSteer.ok && wrongSteer.code === "workspace_mismatch" && !wrongCancel.ok && wrongCancel.code === "workspace_mismatch" && host.runningCount() === 1);
  const refused = await js(`window.agent.run(${JSON.stringify({ sessionId: "same", workspace: b, message: "must stay queued in B", mode: "default" })})`);
  check("真实 host 的接收前拒绝明确回传 accepted:false", !refused.ok && refused.accepted === false);
  const ambiguous = await js("window.agent.runCancel('same')");
  check("旧式裸 id 控制在同名场景拒绝猜目标", !ambiguous.ok && ambiguous.code === "invalid_target");
  const steer = await js(`window.agent.runSteer('same', 'for A', ${JSON.stringify(a)})`);
  check("正确工作区可经真实 IPC 插话", steer.ok && steer.queued === 1);
  const cancel = await js(`window.agent.runCancel('same', ${JSON.stringify(a)})`);
  const result = await js("window.activeRun");
  check("正确工作区取消穿透审批门并收束原运行", cancel.ok && result.aborted === true && host.runningCount() === 0);
  check("真实用户轮已接收后取消仍回传 accepted:true", result.accepted === true);
  const late = await js(`window.agent.runSteer('same', 'too late', ${JSON.stringify(a)})`);
  check("收束后的插话明确拒绝", late.ok === false);
  check("无 preload 错误", errors.length === 0);
  writeFileSync(join(out, "result.json"), JSON.stringify({ checks, errors, wrongSteer, wrongCancel, refused, ambiguous, steer, cancel, result, late }, null, 2));
  await host.orchestrationClose(); win.destroy(); app.exit(checks.every((c) => c.ok) ? 0 : 1);
}
setTimeout(() => { console.error("IPC smoke 超时"); app.exit(1); }, 30000).unref();
main().catch(async (error) => { console.error(error); if (host) await host.orchestrationClose(); app.exit(1); });
